"""Agent A2A integration mixin and base contracts."""
from __future__ import annotations

from typing import Any
from app.a2a.broker import a2a_broker
from app.a2a.protocol import A2AMessage, A2AMessageType, A2AResponse, A2ACapability


class A2AAgentMixin:
    """Mixin giving agents first-class Agent-to-Agent (A2A) capabilities."""

    agent_id: str
    role_description: str = ""
    skills: list[str] = []

    def ask_peer(
        self,
        peer_id: str,
        intent: str,
        payload: dict[str, Any],
        job_id: str | None = None,
        conversation_id: str | None = None,
    ) -> A2AResponse:
        """Send a synchronous structured question to a peer agent."""
        msg = A2AMessage(
            conversation_id=conversation_id or f"conv_{job_id or 'adhoc'}",
            job_id=job_id,
            sender_agent=getattr(self, "name", self.__class__.__name__),
            recipient_agent=peer_id,
            message_type=A2AMessageType.REQUEST,
            intent=intent,
            payload=payload,
        )
        return a2a_broker.send_message(msg)

    def challenge_peer(
        self,
        peer_id: str,
        issue_code: str,
        reason: str,
        facts: dict[str, Any] | None = None,
        job_id: str | None = None,
    ) -> A2AResponse:
        """Challenge an output, calculation, or fact generated by a peer."""
        msg = A2AMessage(
            conversation_id=f"challenge_{job_id or 'adhoc'}",
            job_id=job_id,
            sender_agent=getattr(self, "name", self.__class__.__name__),
            recipient_agent=peer_id,
            message_type=A2AMessageType.CHALLENGE,
            intent="challenge_fact",
            payload={"code": issue_code, "reason": reason, "facts": facts or {}},
        )
        return a2a_broker.send_message(msg)

    def delegate_task(
        self,
        peer_id: str,
        subtask_goal: str,
        params: dict[str, Any] | None = None,
        job_id: str | None = None,
    ) -> A2AResponse:
        """Delegate a specialized sub-task to a peer agent."""
        msg = A2AMessage(
            conversation_id=f"delegate_{job_id or 'adhoc'}",
            job_id=job_id,
            sender_agent=getattr(self, "name", self.__class__.__name__),
            recipient_agent=peer_id,
            message_type=A2AMessageType.DELEGATE,
            intent="execute_subtask",
            payload={"goal": subtask_goal, "params": params or {}},
        )
        return a2a_broker.send_message(msg)

    def discover_peers(self, skill: str | None = None) -> list[A2ACapability]:
        """Find other registered agents with a specific skill."""
        return a2a_broker.discover_agents(skill=skill)
